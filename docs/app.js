function ancestorsOf(id){
  var pre = {}; GRAPH.edges.forEach(function(e){ (pre[e[1]]=pre[e[1]]||[]).push(e[0]); });
  var out={}, stack=[id];
  while(stack.length){
    var n=stack.pop();
    (pre[n]||[]).forEach(function(p){ if(!out[p]){ out[p]=1; stack.push(p); } });
  }
  return out;
}
